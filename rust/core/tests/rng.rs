//! Fixture parity tests for `uvoc_core::rng`.

mod common;

use common::{load, Tolerance};
use uvoc_core::rng::{seed, tau_rand, tau_rand_int, RngState};

fn run_case(case: &str) {
    let fixture = load("rng", case);
    assert_eq!(fixture["component"], "rng");
    let tolerance = Tolerance::parse(&fixture["tolerance"]);

    let s = fixture["inputs"]["seed"].as_i64().expect("inputs.seed");
    let n = fixture["inputs"]["n"].as_u64().expect("inputs.n") as usize;

    let mut state: RngState = [0; 3];
    seed(&mut state, s);

    let initial_state: Vec<i64> = fixture["expected"]["initial_state"]
        .as_array()
        .unwrap()
        .iter()
        .map(|v| v.as_i64().unwrap())
        .collect();
    assert_eq!(state.to_vec(), initial_state, "{case}: initial_state");

    // int_sequence is generated by tau_rand_int on a copy of the state,
    // then float_sequence is generated by tau_rand on a *fresh* seed of the
    // same state (both advance the same seeded state independently) --
    // confirm against the fixture schema: both sequences have length n and
    // both derive from the same initial seed. We replay int_sequence first,
    // then reseed and replay float_sequence, matching how gen_fixtures.py
    // must have produced two independent sequences from the same seed.
    let mut int_state: RngState = [0; 3];
    seed(&mut int_state, s);
    let int_sequence: Vec<i32> = fixture["expected"]["int_sequence"]
        .as_array()
        .unwrap()
        .iter()
        .map(|v| v.as_i64().unwrap() as i32)
        .collect();
    assert_eq!(int_sequence.len(), n, "{case}: int_sequence length");
    for (i, &expected) in int_sequence.iter().enumerate() {
        let actual = tau_rand_int(&mut int_state);
        assert_eq!(actual, expected, "{case}: int_sequence[{i}]");
    }

    let final_int_state: Vec<i64> = fixture["expected"]["final_int_state"]
        .as_array()
        .unwrap()
        .iter()
        .map(|v| v.as_i64().unwrap())
        .collect();
    assert_eq!(
        int_state.to_vec(),
        final_int_state,
        "{case}: final_int_state"
    );

    let mut float_state: RngState = [0; 3];
    seed(&mut float_state, s);
    let float_sequence: Vec<f32> = fixture["expected"]["float_sequence"]
        .as_array()
        .unwrap()
        .iter()
        .map(|v| v.as_f64().unwrap() as f32)
        .collect();
    assert_eq!(float_sequence.len(), n, "{case}: float_sequence length");
    for (i, &expected) in float_sequence.iter().enumerate() {
        let actual = tau_rand(&mut float_state);
        tolerance.assert_close(actual, expected, &format!("{case}: float_sequence[{i}]"));
    }
}

#[test]
fn tau_rand_seed_0() {
    run_case("tau_rand_seed_0");
}

#[test]
fn tau_rand_seed_42() {
    run_case("tau_rand_seed_42");
}

#[test]
fn tau_rand_seed_123456789() {
    run_case("tau_rand_seed_123456789");
}
