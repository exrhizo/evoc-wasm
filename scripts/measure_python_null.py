#!/usr/bin/env python
"""Measure Python evoc's OWN self-agreement across random seeds.

Context (see VALIDATION_PLAN.md section 2A and rust/core/PCA_VALIDATION.md):
Phase 9 ported `evoc_clusters`/`EVoC.fit_predict`, which internally calls
sklearn's randomized PCA whose RNG internals cannot be replayed bit-exactly
in Rust/Zig. So the port is validated via Adjusted Rand Index (ARI) against
real Python output instead of bit-exact fixtures. The existing single-seed
ARI numbers (Rust 0.80 at seed 42, Zig 0.89 at seed 29, with seeds tried
ranging ARI 0.51-0.89) are NOT trustworthy validation on their own -- they
are a single sample each. This script answers a prior question: is Python's
OWN `EVoC.fit_predict` output this variable run-to-run across random seeds,
on the exact same input data? If Python's self-agreement is *also* broad,
then the port's spread is normal algorithm stochasticity, not a port defect.
If Python's self-agreement is tight, the port's spread indicates a real gap.

Uses the EXACT same X (240x24 synthetic cosine-friendly blobs) as
fixtures/clustering/evoc_clusters_e2e_ari_check.json, generated by
scripts/gen_evoc_clusters_ari_fixture.py. Runs
`evoc.EVoC(random_state=s).fit_predict(X)` for s in 0..19 (20 seeds), all
other EVoC constructor args left at the library defaults (matching what the
fixture generator used: n_neighbors=15, n_epochs=50, base_min_cluster_size=5,
min_samples=5, noise_level=0.5). Computes pairwise
sklearn.metrics.adjusted_rand_score across all 20 runs (C(20,2)=190 pairs)
and reports the distribution.

Usage (from repo root):
    /path/to/pyenv/bin/python scripts/measure_python_null.py

Requires numpy, scipy, scikit-learn, numba, tqdm and a working `evoc`
reference on PYTHONPATH (see PORTING.md for the reference clone location).
"""
import itertools
import json
import statistics
import sys
from pathlib import Path

import numpy as np
from sklearn.metrics import adjusted_rand_score

import evoc

REPO_ROOT = Path(__file__).resolve().parent.parent
FIXTURE_PATH = REPO_ROOT / "fixtures" / "clustering" / "evoc_clusters_e2e_ari_check.json"
OUT_PATH = REPO_ROOT / "fixtures" / "clustering" / "python_self_agreement_null.json"

N_SEEDS = 20
SEEDS = list(range(N_SEEDS))


def percentile(sorted_vals, p):
    """Simple linear-interpolation percentile, no numpy dependency needed
    beyond what's already imported."""
    if not sorted_vals:
        return float("nan")
    k = (len(sorted_vals) - 1) * (p / 100.0)
    f = int(k)
    c = min(f + 1, len(sorted_vals) - 1)
    if f == c:
        return sorted_vals[f]
    return sorted_vals[f] + (sorted_vals[c] - sorted_vals[f]) * (k - f)


def main():
    with open(FIXTURE_PATH) as f:
        fixture = json.load(f)

    X = np.array(fixture["data"], dtype=np.float32)
    print(f"Loaded X: shape={X.shape} from {FIXTURE_PATH}", file=sys.stderr)

    all_labels = {}
    for s in SEEDS:
        print(f"Running EVoC(random_state={s}).fit_predict(X)...", file=sys.stderr)
        labels = evoc.EVoC(random_state=s).fit_predict(X)
        all_labels[s] = np.asarray(labels)

    pairwise = []
    for s1, s2 in itertools.combinations(SEEDS, 2):
        ari = adjusted_rand_score(all_labels[s1], all_labels[s2])
        pairwise.append({"seed_a": s1, "seed_b": s2, "ari": float(ari)})

    ari_values = [p["ari"] for p in pairwise]
    ari_sorted = sorted(ari_values)

    summary = {
        "n_pairs": len(ari_values),
        "min": min(ari_values),
        "p25": percentile(ari_sorted, 25),
        "median": percentile(ari_sorted, 50),
        "p75": percentile(ari_sorted, 75),
        "max": max(ari_values),
        "mean": statistics.fmean(ari_values),
        "std": statistics.pstdev(ari_values),
    }

    print("\n=== Python EVoC self-agreement across seeds 0..19 (190 pairs) ===", file=sys.stderr)
    for k, v in summary.items():
        print(f"  {k}: {v}", file=sys.stderr)

    out = {
        "component": "clustering",
        "case": "python_self_agreement_null",
        "note": (
            "Measures Python evoc's OWN run-to-run variability: pairwise "
            "Adjusted Rand Index across evoc.EVoC(random_state=s).fit_predict(X) "
            "for s in 0..19, all other EVoC args at library defaults "
            "(n_neighbors=15, n_epochs=50, base_min_cluster_size=5, "
            "min_samples=5, noise_level=0.5). Uses the exact same X as "
            "fixtures/clustering/evoc_clusters_e2e_ari_check.json (240x24 "
            "synthetic cosine-friendly blobs, 6 clusters, from "
            "scripts/gen_evoc_clusters_ari_fixture.py). This is a NULL "
            "measurement -- it does not involve the Rust/Zig port at all -- "
            "used to establish whether Python's own randomized-PCA-based "
            "EVoC pipeline is inherently this variable seed-to-seed, so the "
            "port's observed ARI spread (Rust 0.80 @ seed 42, Zig 0.89 @ "
            "seed 29, range 0.51-0.89 across seeds tried) can be judged "
            "against a Python-vs-Python baseline rather than in a vacuum. "
            "See VALIDATION_PLAN.md section 2A and rust/core/PCA_VALIDATION.md."
        ),
        "source_fixture": str(FIXTURE_PATH.relative_to(REPO_ROOT)),
        "n_samples": int(X.shape[0]),
        "n_features": int(X.shape[1]),
        "seeds": SEEDS,
        "evoc_version": getattr(evoc, "__version__", "unknown"),
        "pairwise_ari": pairwise,
        "summary": summary,
    }

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT_PATH, "w") as f:
        json.dump(out, f, indent=2)

    print(f"\nWrote {OUT_PATH}", file=sys.stderr)


if __name__ == "__main__":
    main()
